CREATE TABLE markets (
    market_id text PRIMARY KEY,
    condition_id text UNIQUE NOT NULL,
    slug text UNIQUE NOT NULL,
    title text NOT NULL,
    asset text NOT NULL CHECK (asset IN ('BTC','ETH')),
    timeframe integer NOT NULL CHECK (timeframe IN (5,15)),
    start_time timestamptz NOT NULL,
    end_time timestamptz NOT NULL CHECK (end_time > start_time),
    order_acceptance_end_time timestamptz,
    settlement_time timestamptz,
    up_token_id text NOT NULL,
    down_token_id text NOT NULL CHECK (up_token_id <> down_token_id),
    reference_price numeric,
    reference_price_source text,
    resolution_source text NOT NULL,
    settlement_rule text NOT NULL,
    settlement_rule_version text NOT NULL,
    rule_verified boolean NOT NULL,
    rule_changed boolean NOT NULL DEFAULT false,
    twap_window integer,
    fee_schedule_version text,
    tick_size numeric,
    minimum_order_size numeric,
    market_status text NOT NULL,
    accepting_orders boolean NOT NULL,
    resolved_outcome text CHECK (resolved_outcome IN ('UP','DOWN')),
    raw_metadata jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX markets_scope ON markets(asset,timeframe,start_time DESC);
CREATE INDEX markets_recheck ON markets(updated_at) WHERE resolved_outcome IS NULL;
CREATE TABLE market_rule_versions (
    market_id text REFERENCES markets, version text NOT NULL, snapshot jsonb NOT NULL,
    first_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(), PRIMARY KEY(market_id,version)
);
CREATE TABLE fee_schedules (
    version text PRIMARY KEY, schedule jsonb NOT NULL, first_seen_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE engine_events (
    seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id text UNIQUE NOT NULL, market_id text REFERENCES markets,
    source text NOT NULL, kind text NOT NULL, event_time timestamptz NOT NULL,
    received_at timestamptz NOT NULL, processed_at timestamptz NOT NULL,
    persisted_at timestamptz NOT NULL DEFAULT clock_timestamp(), sequence bigint,
    data jsonb NOT NULL, quality_flags text[] NOT NULL DEFAULT '{}'
);
CREATE INDEX engine_market_kind ON engine_events(market_id,kind,seq DESC);
CREATE INDEX engine_received ON engine_events USING brin(received_at);
CREATE INDEX engine_kind_recent ON engine_events(kind,seq DESC);
CREATE TABLE data_source_status (
    source text PRIMARY KEY, status text NOT NULL, last_attempt_at timestamptz NOT NULL,
    last_success_at timestamptz, last_error text
);
CREATE TABLE market_resolutions (
    market_id text PRIMARY KEY REFERENCES markets, outcome text NOT NULL CHECK (outcome IN ('UP','DOWN')),
    rule_version text NOT NULL, source text NOT NULL, event_id text UNIQUE NOT NULL REFERENCES engine_events(event_id),
    received_at timestamptz NOT NULL
);
CREATE TABLE dataset_versions (
    version text PRIMARY KEY, file_path text NOT NULL, sha256 text NOT NULL,
    first_seq bigint NOT NULL, last_seq bigint NOT NULL UNIQUE, event_count bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(first_seq)
);
CREATE VIEW market_snapshots AS SELECT * FROM engine_events WHERE kind='METADATA';
CREATE VIEW orderbook_snapshots AS SELECT * FROM engine_events WHERE kind='BOOK';
CREATE VIEW trade_ticks AS SELECT * FROM engine_events WHERE kind='TRADE';
CREATE VIEW oracle_ticks AS SELECT * FROM engine_events WHERE kind='ORACLE';
CREATE VIEW reference_ticks AS SELECT * FROM engine_events WHERE kind='REFERENCE';
CREATE VIEW data_quality_events AS SELECT * FROM engine_events WHERE cardinality(quality_flags)>0;
